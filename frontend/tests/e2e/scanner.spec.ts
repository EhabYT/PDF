import { test, expect } from '@playwright/test';
import path from 'node:path';
const password = process.env.OWNER_PASSWORD || '';
test('owner can scan, compare, name and export a real document', async ({ page }, testInfo) => {
  test.skip(!password, 'OWNER_PASSWORD environment variable required');
  await page.goto('/');
  await page.getByLabel('Username').fill('owner');
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await expect(page.getByRole('heading', { name: 'Your documents, beautifully clear.' })).toBeVisible();
  await page.getByRole('link', { name: 'NEW SCAN', exact: true }).click();
  await page.locator('input[type="file"]').first().setInputFiles(path.resolve(__dirname, '../fixtures/sample.png'));
  await page.getByRole('button', { name: /Upload 1 file/ }).click();
  await expect(page).toHaveURL(/document\/\?id=/);
  await expect(page.getByText('Completed').first()).toBeVisible({ timeout: 60000 });
  await page.getByRole('button', { name: 'Compare', exact: true }).click();
  await expect(page.getByRole('slider', { name: /Before and after/ })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('document-workspace.png'), fullPage: true });
  await page.getByRole('link', { name: 'Export PDF' }).click();
  await expect(page.getByRole('heading', { name: 'Smart Document Naming' })).toBeVisible();
  await page.getByRole('button', { name: 'Export PDF', exact: true }).click();
  await expect(page.getByText('Export ready')).toBeVisible({ timeout: 60000 });
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download', exact: true }).first().click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toMatch(/\.pdf$/);
  await page.goto('/dashboard/');
  await page.screenshot({ path: testInfo.outputPath('dashboard.png'), fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
  expect(overflow).toBe(false);
});
